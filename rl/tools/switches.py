#!/usr/bin/env python3
"""The environment variables the fork's engine changes add, derived from the code (not written by hand).

    switches.py [--branch REF[=NAME]]... [--base REF]            print the table (markdown)
    switches.py --block | --json
    switches.py --check [FILE ...] [--exceptions FILE]           F5: FILE blocks are fresh; default-on switches are listed
    switches.py --write FILE                                     replace the block of FILE
    options: --root DIR (a checkout; default: the repository that holds this script), --require-block

A switch is a name that a line added to sglang_neuron/ between the merge base with --base and the branch reads from the
environment, and that the base's sglang_neuron/ does not mention at all (a variable upstream already has is not ours).
Reads that are recognised: environ.get("X"[, default]), getenv("X"[, default]), environ["X"] (also through
__import__("os").environ), and zero_or_one(CONST, ...) where CONST = "X" is defined in the same file (the default
is then read from zero_or_one in env_registry.py). Other helper forms are not recognised.
  default  the literal default of the read, or "unset"; the "on" column is yes for 1/true/yes/on, no for unset, 0, false,
           no, off or empty, and "mode" for any other text (a mode name such as auto is not off)
  purpose  the first sentence of the docstring that names the variable in a changed file, else the comment on or above
           the read, else "no description in code"
  branch   the --branch name (REF=NAME shows NAME; default branch HEAD, shown by its checked-out name)
--check fails when a switch whose default is not off is missing from rl/tools/switches_exceptions.txt (lines
"NAME<TAB>reason"; # starts a comment). A FILE without the block is reported and passes, unless --require-block.
Markers: <!-- switches:begin ... --> and <!-- switches:end -->. Exit status: 0 pass, 1 fail, 2 bad input.
"""
import argparse
import ast
import json
import os
import re
import subprocess
import sys

sys.dont_write_bytecode = True

BEGIN = "<!-- switches:begin generated by rl/tools/switches.py from the code; do not edit -->"
END = "<!-- switches:end -->"
BEGIN_RX = re.compile(r"^<!-- switches:begin[^>]*-->[ \t]*$")
END_RX = re.compile(r"^<!-- switches:end -->[ \t]*$")
NAME = r"[A-Z][A-Z0-9_]{4,}"
READ_RX = re.compile(r"(?:environ\.get|getenv)\(\s*(['\"])(" + NAME + r")\1\s*(?:,\s*([^)]*?))?\s*\)")
INDEX_RX = re.compile(r"environ\[\s*(['\"])(" + NAME + r")\1\s*\]")
ZERO_RX = re.compile(r"zero_or_one\(\s*([A-Za-z_][A-Za-z0-9_]*)")
OFF = {"", "0", "false", "no", "off"}
ON = {"1", "true", "yes", "on"}
BASE_CANDIDATES = ("origin/upstream-main", "fork/upstream-main", "upstream-main")


class BadInput(Exception):
    pass


def default_root():
    return os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def git(root, *args):
    r = subprocess.run(["git", "-c", "core.quotepath=false", "-C", root] + list(args), stdout=subprocess.PIPE,
                       stderr=subprocess.PIPE)
    if r.returncode != 0:
        raise BadInput("git %s failed: %s" % (" ".join(args), r.stderr.decode("utf-8", "replace").strip()))
    return r.stdout.decode("utf-8", "replace")


def resolves(root, ref):
    r = subprocess.run(["git", "-C", root, "rev-parse", "--verify", "--quiet", ref + "^{commit}"],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return r.returncode == 0


def find_base(root, base):
    for cand in ([base] if base else BASE_CANDIDATES):
        if resolves(root, cand):
            return cand
    raise BadInput("no base ref found (tried %s); pass --base" % ", ".join([base] if base else BASE_CANDIDATES))


def show(root, ref, path):
    r = subprocess.run(["git", "-C", root, "show", "%s:%s" % (ref, path)], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return r.stdout.decode("utf-8", "replace") if r.returncode == 0 else None


def base_names(root, base):
    r = subprocess.run(["git", "-C", root, "grep", "-h", "-o", "-E", NAME, base, "--", "sglang_neuron"],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return set(r.stdout.decode("utf-8", "replace").split())


def added_lines(root, base, ref):
    """{path: [added line, ...]} of sglang_neuron/**/*.py between the merge base of base and ref, and ref."""
    out = git(root, "diff", "-U0", "--no-color", "--no-renames", "%s...%s" % (base, ref), "--", "sglang_neuron")
    res, cur = {}, None
    for line in out.split("\n"):
        if line.startswith("+++ "):
            cur = line[6:] if line.startswith("+++ b/") else None
            if cur is not None and not cur.endswith(".py"):
                cur = None
            if cur is not None:
                res.setdefault(cur, [])
        elif cur is not None and line.startswith("+") and not line.startswith("+++"):
            res[cur].append(line[1:])
    return res


def literal(text):
    """(default text, kind) of the second argument of a read."""
    if text is None or text == "":
        return "unset"
    t = text.strip()
    m = re.match(r"^(['\"])(.*)\1$", t)
    return m.group(2) if m else t


def on_state(default):
    d = default.strip().lower()
    if default == "unset" or d in OFF:
        return "no"
    if d in ON:
        return "yes"
    return "mode"


def zero_or_one_default(root, ref):
    text = show(root, ref, "sglang_neuron/env_registry.py") or ""
    m = re.search(r"def zero_or_one\(.*?\n(?=def |\Z)", text, re.S)
    if m:
        d = re.search(r"environ\.get\(\s*name\s*,\s*(['\"])(.*?)\1", m.group(0))
        if d:
            return d.group(2)
    return None


def first_sentence(doc, name):
    doc = " ".join(doc.split())
    i = doc.find(name + ":")
    if i >= 0:
        doc = doc[i + len(name) + 1:].strip()
    else:
        doc = re.sub(r"^RLKIT:\s*", "", doc)
    cut = len(doc)
    for sep in ("; ", ". "):
        j = doc.find(sep)
        if j >= 0:
            cut = min(cut, j)
    s = doc[:cut].rstrip(".")
    if len(s) > 140:
        s = s[:140].rsplit(" ", 1)[0] + "..."
    return s


def purpose_of(name, texts, lines_by_file):
    for path, text in texts.items():
        try:
            tree = ast.parse(text)
        except (SyntaxError, ValueError):
            continue
        for node in [tree] + [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))]:
            doc = ast.get_docstring(node)
            if doc and name in doc:
                return first_sentence(doc, name)
    for path, text in texts.items():
        lines = text.split("\n")
        for i, l in enumerate(lines):
            if name in l and (READ_RX.search(l) or INDEX_RX.search(l)):
                block, j = [], i - 1
                while j >= 0 and lines[j].strip().startswith("#"):
                    block.insert(0, lines[j].strip().lstrip("# "))
                    j -= 1
                m = re.search(r"#\s*(.+)$", l)
                if m:
                    block.append(m.group(1))
                if block:
                    joined = " ".join(block)
                    k = joined.find(name)
                    return first_sentence(joined[k:] if k >= 0 else joined, name)
    return "no description in code"


def derive(root, base, ref):
    """[{name, default, on, purpose, file}] for one branch."""
    if not resolves(root, ref):
        raise BadInput("no such ref: %s" % ref)
    seen = base_names(root, base)
    added = added_lines(root, base, ref)
    zdef = None
    found = {}
    texts = {}
    for path, lines in added.items():
        text = show(root, ref, path)
        if text is None:
            continue
        texts[path] = text
        for l in lines:
            for m in READ_RX.finditer(l):
                found.setdefault(m.group(2), (path, literal(m.group(3))))
            for m in INDEX_RX.finditer(l):
                found.setdefault(m.group(2), (path, "unset"))
            for m in ZERO_RX.finditer(l):
                c = re.search(r"^%s\s*=\s*(['\"])(%s)\1" % (re.escape(m.group(1)), NAME), text, re.M)
                if c:
                    if zdef is None:
                        zdef = zero_or_one_default(root, ref) or "0"
                    found.setdefault(c.group(2), (path, zdef))
    res = []
    for name in sorted(found):
        if name in seen:
            continue
        path, d = found[name]
        res.append({"name": name, "default": d, "on": on_state(d), "purpose": purpose_of(name, texts, None), "file": path})
    return res


def read_exceptions(path):
    names = {}
    try:
        with open(path, "r", encoding="utf-8") as fh:
            for line in fh.read().replace("\r\n", "\n").split("\n"):
                if not line.strip() or line.lstrip().startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) < 2 or not parts[1].strip():
                    raise BadInput("%s: an entry needs NAME<TAB>reason: %r" % (path, line))
                names[parts[0].strip()] = parts[1].strip()
    except OSError:
        pass
    return names


def collect(root, base, branches):
    """merged list of switches over the branches, each with a 'branches' list."""
    merged = {}
    for ref, label in branches:
        for s in derive(root, base, ref):
            e = merged.setdefault(s["name"], dict(s, branches=[]))
            if label not in e["branches"]:
                e["branches"].append(label)
    return [merged[k] for k in sorted(merged)]


def render_rows(sw):
    out = ["| Variable | Default | On by default | Purpose | Branch |", "|---|---|---|---|---|"]
    if not sw:
        out.append("| (none) | | | | |")
    for s in sw:
        out.append("| `%s` | `%s` | %s | %s | %s |" % (s["name"], s["default"], s["on"], s["purpose"].replace("|", "/"),
                                                     ", ".join("`%s`" % b for b in s["branches"])))
    return "\n".join(out)


def render_block(sw):
    return BEGIN + "\n" + render_rows(sw) + "\n" + END


def find_block(lines):
    b = [i for i, l in enumerate(lines) if BEGIN_RX.match(l)]
    e = [i for i, l in enumerate(lines) if END_RX.match(l)]
    if not b and not e:
        return None
    if len(b) != 1 or len(e) != 1 or e[0] < b[0]:
        raise BadInput("expected exactly one begin line followed by one end line")
    return b[0], e[0]


def read_doc(root, rel):
    try:
        with open(os.path.join(root, *rel.split("/")), "rb") as fh:
            return fh.read().decode("utf-8")
    except (OSError, UnicodeDecodeError) as e:
        raise BadInput("cannot read %s: %s" % (rel, e))


def split_keep(text):
    """(lines without their line end, the file's line end). A file that mixes CRLF and LF is refused: a block pasted
    with the other line end would otherwise not be found, and the check would pass without looking."""
    crlf = text.count("\r\n")
    if crlf and text.count("\n") != crlf:
        raise BadInput("mixed line endings (CRLF and LF); make them one kind")
    return [l[:-1] if l.endswith("\r") else l for l in text.split("\n")], ("\r\n" if crlf else "\n")


def branch_specs(root, specs):
    out = []
    for s in specs or ["HEAD"]:
        ref, _, label = s.partition("=")
        if not label:
            label = ref
            if ref == "HEAD":
                label = git(root, "rev-parse", "--abbrev-ref", "HEAD").strip()
            else:
                label = re.sub(r"^(?:origin|fork|upstream)/", "", ref)
        out.append((ref, label))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=default_root())
    ap.add_argument("--base")
    ap.add_argument("--branch", action="append")
    ap.add_argument("--block", action="store_true")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--check", nargs="*", metavar="FILE")
    ap.add_argument("--write", metavar="FILE")
    ap.add_argument("--exceptions", default=os.path.join("rl", "tools", "switches_exceptions.txt"))
    ap.add_argument("--require-block", action="store_true")
    a = ap.parse_args(argv)
    try:
        base = find_base(a.root, a.base)
        sw = collect(a.root, base, branch_specs(a.root, a.branch))
        if a.check is not None:
            problems, notes = [], []
            exc = read_exceptions(os.path.join(a.root, a.exceptions))
            for s in sw:
                if s["on"] != "no" and s["name"] not in exc:
                    problems.append("%s: default %s is not off and %s has no entry for it (name and reason)"
                                    % (s["name"], s["default"], a.exceptions.replace("\\", "/")))
            want = render_block(sw)
            for rel in a.check:
                try:
                    lines, _ = split_keep(read_doc(a.root, rel))
                    pos = find_block(lines)
                except BadInput as e:
                    problems.append("%s: %s" % (rel, e))
                    continue
                if pos is None:
                    if a.require_block:
                        problems.append("%s: no switches block (markers missing)" % rel)
                    else:
                        notes.append("%s: no switches block, not checked" % rel)
                elif "\n".join(l.rstrip("\r") for l in lines[pos[0]:pos[1] + 1]) != want:
                    problems.append("%s: the switches block is stale; run: python rl/tools/switches.py --write %s" % (rel, rel))
            for n in notes:
                print(n)
            for p in problems:
                print("switches: " + p)
            print("switches.py --check: %d switches, %s" % (len(sw), "FAIL" if problems else "PASS"))
            return 1 if problems else 0
        if a.write:
            lines, eol = split_keep(read_doc(a.root, a.write))
            pos = find_block(lines)
            if pos is None:
                raise BadInput("%s has no switches block markers" % a.write)
            new = lines[:pos[0]] + render_block(sw).split("\n") + lines[pos[1] + 1:]
            with open(os.path.join(a.root, *a.write.split("/")), "wb") as fh:
                fh.write(eol.join(new).encode("utf-8"))
            print("wrote the switches block of %s" % a.write)
        elif a.json:
            for s in sw:
                print(json.dumps(s, sort_keys=True))
        elif a.block:
            print(render_block(sw))
        else:
            print(render_rows(sw))
        return 0
    except BadInput as e:
        print("switches: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
