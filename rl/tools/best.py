#!/usr/bin/env python3
"""The headline numbers of the fork: rl/best.tsv is their single source; this script reads the result files.

    best.py                       print the table (markdown)
    best.py --block               print the table between the two marker lines
    best.py --json                one JSON object per row (key, label, model, values, files, baseline, tier)
    best.py --check [FILE ...]    F5: every row is sound; each FILE that holds a block equals the rendering
    best.py --write FILE          replace the block of FILE (it must hold both marker lines)
    options: --root DIR (the repository root; default: two folders above this script), --require-block

rl/best.tsv columns (tab separated, one header line): key, label, model, file, selector, baseline, tier.
  file      one or more paths under rl/data, separated by ';' (one per pass of one server start)
  selector  <csv column>:<csv column>=<value>, for example output_token_throughput_tps:concurrency=32
  baseline  the key of another row, or '-'
  tier      screen, or paired(<n>)  (rl/METHOD.md): the tier is always printed, so a number cannot lose it
A row is sound when its key is unique, its tier is valid, its baseline exists, no label cites a hub row id, and every
file exists, holds exactly one cell for the selector, with a finite number, and that cell has no failed request.
A difference between a row and its baseline is not printed as a percentage. At tier screen a row whose mean is within
10 percent of its baseline's mean is marked "not distinguished at screen tier" (rl/METHOD.md, tiers).
Markers in a document: <!-- best:begin ... --> and <!-- best:end -->. A FILE named to --check that has no block is
reported and passes, unless --require-block is given. Exit status: 0 pass, 1 fail, 2 bad input.
"""
import argparse
import csv
import json
import math
import os
import re
import sys

sys.dont_write_bytecode = True

COLUMNS = ["key", "label", "model", "file", "selector", "baseline", "tier"]
TIER_RX = re.compile(r"^(screen|paired\([1-9][0-9]*\))$")
KEY_RX = re.compile(r"^[a-z0-9][a-z0-9_]*$")
HUB_ID_RX = re.compile(r"\bL-(?:I\d+-\d+|\d{3})\b|trainium-rl-hub")
BEGIN = "<!-- best:begin generated by rl/tools/best.py from rl/best.tsv; do not edit -->"
END = "<!-- best:end -->"
BEGIN_RX = re.compile(r"^<!-- best:begin[^>]*-->[ \t]*$")
END_RX = re.compile(r"^<!-- best:end -->[ \t]*$")
UNITS = {"output_token_throughput_tps": ("tok/s", 1), "ttft_p50_s": ("s", 3)}
SCREEN_MIN_DIFF = 0.10   # METHOD.md: a gain claim may rest on screen tier only at 10 percent or more (provisional)


class BadInput(Exception):
    pass


def default_root():
    return os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def read_rows(root):
    path = os.path.join(root, "rl", "best.tsv")
    try:
        with open(path, "r", encoding="utf-8", newline="") as fh:
            text = fh.read()
    except OSError as e:
        raise BadInput("cannot read %s: %s" % (path, e))
    lines = [l for l in text.replace("\r\n", "\n").split("\n") if l != ""]
    if not lines or lines[0].split("\t") != COLUMNS:
        raise BadInput("rl/best.tsv: the first line must be the header %s" % "\t".join(COLUMNS))
    rows = []
    for n, line in enumerate(lines[1:], 2):
        cells = line.split("\t")
        if len(cells) != len(COLUMNS):
            raise BadInput("rl/best.tsv line %d: %d cells, expected %d" % (n, len(cells), len(COLUMNS)))
        rows.append(dict(zip(COLUMNS, cells)))
    return rows


def read_cell(root, rel, selector):
    """(value, error): the selected number of one csv file."""
    if ":" not in selector or "=" not in selector.split(":", 1)[1]:
        return None, "selector %r is not <column>:<column>=<value>" % selector
    col, cond = selector.split(":", 1)
    fcol, want = cond.split("=", 1)
    path = os.path.join(root, "rl", "data", *rel.split("/"))
    if not os.path.isfile(path):
        return None, "%s does not exist" % rel
    try:
        with open(path, "r", encoding="utf-8", newline="") as fh:
            rows = list(csv.DictReader(fh))
    except (OSError, UnicodeDecodeError, csv.Error) as e:
        return None, "%s cannot be read: %s" % (rel, e)
    if not rows or col not in rows[0] or fcol not in rows[0]:
        return None, "%s has no column %s or %s" % (rel, col, fcol)
    hits = []
    for r in rows:
        try:
            if float(r[fcol]) == float(want):
                hits.append(r)
        except (TypeError, ValueError):
            if r[fcol] == want:
                hits.append(r)
    if len(hits) != 1:
        return None, "%s: %d rows have %s=%s (need exactly 1)" % (rel, len(hits), fcol, want)
    r = hits[0]
    try:
        v = float(r[col])
    except (TypeError, ValueError):
        return None, "%s: %s is %r, not a number" % (rel, col, r[col])
    if not math.isfinite(v):
        return None, "%s: %s is not finite" % (rel, col)
    for bad in ("n_error",):
        if bad in r and r[bad] not in ("", "0", "0.0"):
            return None, "%s: the cell has %s=%s; a cell with a failed request is not a headline" % (rel, bad, r[bad])
    return v, None


def load(root):
    """(rows with values, problems)."""
    rows = read_rows(root)
    problems, seen = [], set()
    keys = [r["key"] for r in rows]
    for r in rows:
        k = r["key"]
        if not KEY_RX.match(k):
            problems.append("%s: key must match [a-z0-9_]+" % k)
        if k in seen:
            problems.append("%s: duplicate key" % k)
        seen.add(k)
        if not TIER_RX.match(r["tier"]):
            problems.append("%s: tier %r is not screen or paired(<n>)" % (k, r["tier"]))
        if r["baseline"] != "-" and r["baseline"] not in keys:
            problems.append("%s: baseline %r is not a key of rl/best.tsv" % (k, r["baseline"]))
        if r["baseline"] == k:
            problems.append("%s: a row cannot be its own baseline" % k)
        for col in ("label", "model"):
            if HUB_ID_RX.search(r[col]):
                problems.append("%s: %s cites a hub row id or the hub" % (k, col))
        metric = r["selector"].split(":", 1)[0]
        if metric not in UNITS:
            problems.append("%s: metric %r is not one of %s" % (k, metric, ", ".join(sorted(UNITS))))
            r["files"], r["values"] = [], []
            continue
        r["files"] = [f for f in r["file"].split(";") if f]
        if not r["files"]:
            problems.append("%s: no file" % k)
        r["values"] = []
        for f in r["files"]:
            if f.startswith(("/", "rl/")) or ".." in f.split("/"):
                problems.append("%s: file %r must be a path under rl/data" % (k, f))
                continue
            v, err = read_cell(root, f, r["selector"])
            if err:
                problems.append("%s: %s" % (k, err))
            else:
                r["values"].append(v)
    return rows, problems


def fmt(v, metric):
    unit, dec = UNITS.get(metric, ("", 1))
    return ("{:,.%df}" % dec).format(v)


def metric_of(row):
    return row["selector"].split(":", 1)[0]


def values_text(row):
    m = metric_of(row)
    unit = UNITS.get(m, ("", 1))[0]
    cond = row["selector"].split(":", 1)[1].replace("=", " ")
    txt = " and ".join(fmt(v, m) for v in row["values"])
    return ("%s %s at %s" % (txt, unit, cond)).replace("  ", " ")


def mean(vs):
    return sum(vs) / len(vs)


def common_dir(files):
    dirs = [f.rsplit("/", 1)[0] if "/" in f else "" for f in files]
    return dirs[0] if len(set(dirs)) == 1 else ""


def files_text(row):
    files = row["files"]
    d = common_dir(files)
    if d:
        return "`rl/data/%s/`: %s" % (d, ", ".join("`%s`" % f.rsplit("/", 1)[1] for f in files))
    return ", ".join("`rl/data/%s`" % f for f in files)


def render_rows(rows):
    by = {r["key"]: r for r in rows}
    out = ["| Key | Model | Configuration | Value | Baseline | Tier | Files |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        base = "-"
        note = ""
        b = by.get(r["baseline"])
        if b is not None and b["values"]:
            base = "%s: %s" % (b["key"], values_text(b))
            if r["tier"] == "screen" and r["values"] and mean(b["values"]) != 0:
                if abs(mean(r["values"]) / mean(b["values"]) - 1) < SCREEN_MIN_DIFF:
                    note = "; not distinguished at screen tier"
        out.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            r["key"], r["model"], r["label"], values_text(r) + note if r["values"] else "-", base, r["tier"],
            files_text(r)))
    return "\n".join(out)


def render_block(rows):
    return BEGIN + "\n" + render_rows(rows) + "\n" + END


def find_block(lines):
    """(begin index, end index) of the block, or None; raises BadInput on a broken pair."""
    b = [i for i, l in enumerate(lines) if BEGIN_RX.match(l)]
    e = [i for i, l in enumerate(lines) if END_RX.match(l)]
    if not b and not e:
        return None
    if len(b) != 1 or len(e) != 1 or e[0] < b[0]:
        raise BadInput("expected exactly one begin line followed by one end line")
    return b[0], e[0]


def read_doc(root, rel):
    path = os.path.join(root, *rel.split("/"))
    try:
        with open(path, "rb") as fh:
            return fh.read().decode("utf-8")
    except (OSError, UnicodeDecodeError) as e:
        raise BadInput("cannot read %s: %s" % (rel, e))


def split_keep(text):
    """(lines without their line end, the file's line end). A file that mixes CRLF and LF is refused: a block pasted
    with the other line end would otherwise not be found, and the check would pass without looking."""
    crlf = text.count("\r\n")
    if crlf and text.count("\n") != crlf:
        raise BadInput("mixed line endings (CRLF and LF); make them one kind")
    return [l[:-1] if l.endswith("\r") else l for l in text.split("\n")], ("\r\n" if crlf else "\n")


def check_doc(root, rel, rows, require):
    try:
        lines, _ = split_keep(read_doc(root, rel))
        pos = find_block(lines)
    except BadInput as e:
        return ["%s: %s" % (rel, e)], None
    if pos is None:
        return (["%s: no best block (markers missing)" % rel] if require else []), "%s: no best block, not checked" % rel
    cur = "\n".join(l.rstrip("\r") for l in lines[pos[0]:pos[1] + 1])
    if cur != render_block(rows):
        return ["%s: the best block is stale; run: python rl/tools/best.py --write %s" % (rel, rel)], None
    return [], None


def write_doc(root, rel, rows):
    text = read_doc(root, rel)
    lines, eol = split_keep(text)
    pos = find_block(lines)
    if pos is None:
        raise BadInput("%s has no best block markers" % rel)
    new = lines[:pos[0]] + render_block(rows).split("\n") + lines[pos[1] + 1:]
    with open(os.path.join(root, *rel.split("/")), "wb") as fh:
        fh.write(eol.join(new).encode("utf-8"))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=default_root())
    ap.add_argument("--block", action="store_true")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--check", nargs="*", metavar="FILE")
    ap.add_argument("--write", metavar="FILE")
    ap.add_argument("--require-block", action="store_true")
    a = ap.parse_args(argv)
    try:
        rows, problems = load(a.root)
        if a.check is not None:
            notes = []
            for rel in a.check:
                p, n = check_doc(a.root, rel, rows, a.require_block) if not problems else ([], None)
                problems += p
                if n:
                    notes.append(n)
            for n in notes:
                print(n)
            for p in problems:
                print("best: " + p)
            print("best.py --check: %d rows, %s" % (len(rows), "FAIL" if problems else "PASS"))
            return 1 if problems else 0
        if problems:
            for p in problems:
                print("best: " + p, file=sys.stderr)
            return 1
        if a.write:
            write_doc(a.root, a.write, rows)
            print("wrote the best block of %s" % a.write)
        elif a.json:
            for r in rows:
                print(json.dumps({"key": r["key"], "label": r["label"], "model": r["model"], "values": r["values"],
                                  "files": ["rl/data/" + f for f in r["files"]], "baseline": r["baseline"],
                                  "tier": r["tier"], "selector": r["selector"]}, sort_keys=True))
        elif a.block:
            print(render_block(rows))
        else:
            print(render_rows(rows))
        return 0
    except BadInput as e:
        print("best: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
